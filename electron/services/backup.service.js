'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { app, shell, dialog } = require('electron');
const Database = require('better-sqlite3');
const { getDb, initDatabase, closeDatabase, backupDir, dbFile } = require('../db/connection');
const { validate, ValidationError, AppError, helpers } = require('./validation');
const audit = require('./audit.service');
const { logger } = require('../logger');

/**
 * Backup and restore.
 *
 * A backup is a real SQLite file produced by SQLite's own online backup API,
 * so it is consistent even while the app is being used. Restoring replaces the
 * live database and re-runs migrations, which means a backup taken on an older
 * schema comes back up correctly rather than exploding on a missing column.
 */

const PREFIX = 'school-backup-';
const SUFFIX = '.db';
const KEEP_AUTOMATIC = 7;

/** Only an admin may touch backups - they hold every record in the school. */
function assertAdmin(session) {
  if (!session || session.role !== 'admin') throw new AppError('FORBIDDEN', 'FORBIDDEN');
}

/** Backups are generated by us - a filename from the renderer is never trusted. */
function safeBackupName(name) {
  const raw = String(name || '');
  if (!raw.startsWith(PREFIX) || !raw.endsWith(SUFFIX)) throw new ValidationError({ name: 'invalid' });
  const base = raw.slice(PREFIX.length, -SUFFIX.length);
  if (!/^\d{4}-\d{2}-\d{2}-\d{6}(-[a-z0-9-]{1,32})?$/.test(base)) {
    throw new ValidationError({ name: 'invalid' });
  }
  return raw;
}

function stamp(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return (
    `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}` +
    `-${p(date.getHours())}${p(date.getMinutes())}${p(date.getSeconds())}`
  );
}

function describe(file) {
  const stat = fs.statSync(file.path);
  return {
    name: file.name,
    path: file.path,
    size: stat.size,
    sizeLabel: `${(stat.size / (1024 * 1024)).toFixed(2)} MB`,
    createdAt: stat.mtime.toISOString(),
    kind: file.name.includes('-auto') ? 'automatic' : 'manual',
  };
}

function scan() {
  if (!fs.existsSync(backupDir())) return [];
  return fs
    .readdirSync(backupDir())
    .filter((name) => name.startsWith(PREFIX) && name.endsWith(SUFFIX))
    .sort()
    .reverse()
    .map((name) => describe({ name, path: path.join(backupDir(), name) }));
}

// ---------------------------------------------------------------------------
// Listing and info
// ---------------------------------------------------------------------------

function list(session) {
  assertAdmin(session);
  return { folder: backupDir(), rows: scan() };
}

/** Where things live and how big they are - shown on the backup screen. */
function info(session) {
  assertAdmin(session);
  const live = dbFile();
  const stat = fs.existsSync(live) ? fs.statSync(live) : null;
  const rows = scan();
  return {
    dataFolder: app.getPath('userData'),
    databaseFile: live,
    databaseSize: stat ? stat.size : 0,
    databaseSizeLabel: stat ? `${(stat.size / (1024 * 1024)).toFixed(2)} MB` : '0 MB',
    backupFolder: backupDir(),
    backups: rows.length,
    lastBackup: rows[0]?.createdAt || null,
    lastBackupName: rows[0]?.name || null,
    version: app.getVersion(),
  };
}

// ---------------------------------------------------------------------------
// Creating a backup
// ---------------------------------------------------------------------------

async function create({ note = '' } = {}, session) {
  assertAdmin(session);
  const clean = validate({ note }, { note: helpers.text({ max: 32, lowercase: true }) });

  fs.mkdirSync(backupDir(), { recursive: true });
  // A note made entirely of punctuation strips to nothing; an empty slug would
  // produce a filename safeBackupName can never match again.
  const body = (clean.note || '').replace(/[^a-z0-9-]/g, '').slice(0, 32);
  const slug = body ? `-${body}` : '';
  const name = `${PREFIX}${stamp()}${slug}${SUFFIX}`;
  const target = path.join(backupDir(), name);

  await getDb().backup(target);

  audit.log({ action: 'backup.create', entity: 'backups', entityId: name, details: { note: clean.note || null }, session });
  logger.info(`backup created: ${name}`);
  return { name, ...describe({ name, path: target }) };
}

/**
 * One automatic backup per day, taken at launch, keeping the last seven.
 * Failures are logged and swallowed: a backup problem must never stop the app.
 */
async function runAutomaticBackup() {
  try {
    const today = new Date().toISOString().slice(0, 10);
    // Only an automatic backup already taken today blocks this one - a manual
    // backup from the same day must not suppress the daily safety copy.
    const existing = scan().find((row) => row.kind === 'automatic' && row.name.startsWith(`${PREFIX}${today}`));
    if (existing) return { skipped: true, name: existing.name };

    fs.mkdirSync(backupDir(), { recursive: true });
    const name = `${PREFIX}${stamp()}-auto${SUFFIX}`;
    await getDb().backup(path.join(backupDir(), name));

    pruneAutomatic();
    logger.info(`automatic backup created: ${name}`);
    return { skipped: false, name };
  } catch (err) {
    logger.error('automatic backup failed', err);
    return { skipped: true, error: err.message };
  }
}

function pruneAutomatic() {
  const automatic = scan().filter((row) => row.kind === 'automatic');
  for (const row of automatic.slice(KEEP_AUTOMATIC)) {
    try {
      fs.unlinkSync(row.path);
    } catch (err) {
      logger.warn(`could not prune backup ${row.name}`, err);
    }
  }
}

// ---------------------------------------------------------------------------
// Restoring
// ---------------------------------------------------------------------------

/**
 * Confirms a file really is a usable school database before we ever let it
 * near the live copy. Restoring the wrong file would otherwise destroy every
 * record in the school, so this runs on both the import path and the restore
 * path.
 */
function assertUsableDatabase(file) {
  let probe;
  try {
    probe = new Database(file, { readonly: true, fileMustExist: true });
    const master = probe.prepare(`SELECT name FROM sqlite_master WHERE type = 'table' LIMIT 1`).get();
    if (!master) throw new AppError('INVALID_FILE', 'INVALID_FILE');
    const check = probe.pragma('integrity_check', { simple: true });
    if (String(check).toLowerCase() !== 'ok') throw new AppError('INVALID_FILE', 'INVALID_FILE');
  } catch (err) {
    if (err instanceof AppError) throw err;
    throw new AppError('INVALID_FILE', 'INVALID_FILE');
  } finally {
    if (probe) {
      try {
        probe.close();
      } catch {
        /* the file may be read-only; nothing to do */
      }
    }
  }
}

/**
 * Restores a backup over the live database.
 *
 * The current database is copied aside first, so a restore can itself be
 * undone. After the swap the connection is reopened and migrations re-applied,
 * which is what makes an older backup safe to restore.
 */
async function restore({ name } = {}, session) {
  assertAdmin(session);
  const clean = validate({ name }, { name: helpers.text({ required: true, max: 80 }) });
  const safeName = safeBackupName(clean.name);

  const source = path.join(backupDir(), safeName);
  if (!fs.existsSync(source)) throw new AppError('NOT_FOUND', 'NOT_FOUND');
  assertUsableDatabase(source);

  const live = dbFile();
  const safety = path.join(backupDir(), `${PREFIX}${stamp()}-prerestore${SUFFIX}`);
  fs.mkdirSync(backupDir(), { recursive: true });

  closeDatabase();
  fs.copyFileSync(live, safety);

  // WAL side files belong to the replaced database - clear them or SQLite
  // will happily replay stale pages on top of the restored file.
  for (const suffix of ['-wal', '-shm']) {
    const file = `${live}${suffix}`;
    if (fs.existsSync(file)) fs.unlinkSync(file);
  }
  fs.copyFileSync(source, live);

  initDatabase({ seed: false });

  audit.log({
    action: 'backup.restore',
    entity: 'backups',
    entityId: safeName,
    details: { safetyCopy: path.basename(safety) },
    session,
  });
  logger.info(`backup restored from ${safeName}`);

  return { restored: safeName, safetyCopy: path.basename(safety) };
}

/** Copies a file the admin picked into the backup folder, then verifies it. */
async function importFromFile(session) {
  assertAdmin(session);
  const picked = await dialog.showOpenDialog({
    title: 'Choose a school database backup',
    defaultPath: backupDir(),
    filters: [{ name: 'SQLite database', extensions: ['db', 'sqlite', 'sqlite3'] }],
    properties: ['openFile'],
  });
  if (picked.canceled || !picked.filePaths[0]) return { canceled: true };

  const source = picked.filePaths[0];
  assertUsableDatabase(source);

  const name = `${PREFIX}${stamp()}-imported${SUFFIX}`;
  const target = path.join(backupDir(), name);
  fs.mkdirSync(backupDir(), { recursive: true });
  fs.copyFileSync(source, target);

  audit.log({ action: 'backup.import', entity: 'backups', entityId: name, details: { from: path.basename(source) }, session });
  return { canceled: false, name };
}

// ---------------------------------------------------------------------------
// Removing and opening
// ---------------------------------------------------------------------------

function remove({ name } = {}, session) {
  assertAdmin(session);
  const clean = validate({ name }, { name: helpers.text({ required: true, max: 80 }) });
  const safeName = safeBackupName(clean.name);
  const target = path.join(backupDir(), safeName);
  if (!fs.existsSync(target)) throw new AppError('NOT_FOUND', 'NOT_FOUND');

  fs.unlinkSync(target);
  audit.log({ action: 'backup.delete', entity: 'backups', entityId: safeName, session });
  return { ok: true };
}

function openFolder(session) {
  assertAdmin(session);
  fs.mkdirSync(backupDir(), { recursive: true });
  shell.openPath(backupDir());
  audit.log({ action: 'backup.openFolder', entity: 'backups', session });
  return { opened: true };
}

module.exports = {
  list,
  info,
  create,
  restore,
  importFromFile,
  remove,
  openFolder,
  runAutomaticBackup,
  KEEP_AUTOMATIC,
};